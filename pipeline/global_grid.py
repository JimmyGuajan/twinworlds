"""
TwinWorlds – global prospecting grid
------------------------------------
Fingerprints the WHOLE land surface so the app can paint a heat map of
"how Moon-like / Mars-like is every place on Earth" and point to analog
regions nobody has catalogued.

  1. NASA POWER *regional* climatology, one 10°x10° box and one parameter per request
     (the API's limit), for every box that contains land. Each response holds every
     native 0.5° x 0.625° grid point with its MERRA-2 surface elevation (0 = ocean).
  2. The native points are thinned to a 2.5° land grid (2.5 = 5 x 0.5 = 4 x 0.625).
  The map scores the 6 NASA POWER climate axes (no relief / terrain).

The script is polite and resumable: 3 boxes in flight, and it backs off on HTTP 429.
js/grid.js is rewritten every 10 boxes, so the map fills in while the job runs.

Output: js/grid.js -> window.TW_GRID = {step, cols, rows}     cache: data/grid_cache.json
"""
import json
import ssl
import threading
import time
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / "data" / "grid_cache.json"
OUT = ROOT / "js" / "grid.js"
STEP = 2.5
CTX = ssl.create_default_context()
URL = ("https://power.larc.nasa.gov/api/temporal/climatology/regional?latitude-min={a0}&latitude-max={a1}"
       "&longitude-min={o0}&longitude-max={o1}&parameters={p}&community=RE&format=JSON")
PARAMS = ["T2M", "T2M_RANGE", "PRECTOTCORR", "RH2M", "PS", "ALLSKY_SFC_SW_DWN", "ALLSKY_SFC_UV_INDEX"]
COLS = ["lat", "lon", "t2m", "t2m_range", "precip", "rh", "ps", "sw", "sw_min", "sw_max", "uv", "grid_elev"]
COARSE = ["ALLSKY_SFC_SW_DWN", "ALLSKY_SFC_UV_INDEX"]  # CERES SYN1deg, 1° grid
MONTHS = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"]


def get(url):
    for attempt in range(40):
        try:
            with urllib.request.urlopen(url, timeout=180, context=CTX) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            wait = 90 if e.code == 429 else 10
            print(f"   HTTP {e.code}, waiting {wait}s")
            time.sleep(wait)
        except Exception as e:
            print(f"   {e}, waiting 15s")
            time.sleep(15)
    raise RuntimeError("POWER unreachable")


def on_grid(lat, lon):
    # multiples of 2.5° coincide with native POWER points (2.5 = 5 x 0.5 lat, 4 x 0.625 lon)
    return abs(lat / STEP - round(lat / STEP)) < 1e-6 and abs(lon / STEP - round(lon / STEP)) < 1e-6


def write_grid(data):
    rows = []
    for key, v in sorted(data.items()):
        if len(v) < len(PARAMS) + 1:
            continue
        a, b = map(float, key.split(","))
        rows.append([a, b, v["T2M"], v["T2M_RANGE"], v["PRECTOTCORR"], v["RH2M"], v["PS"], v["SW"], v["SW_MIN"], v["SW_MAX"], v["ALLSKY_SFC_UV_INDEX"], v["z"]])
    OUT.write_text("// AUTO-GENERATED by pipeline/global_grid.py – NASA POWER 2001-2025 climatology on a 2.5° land grid\n"
                   "window.TW_GRID = " + json.dumps({"step": STEP, "cols": COLS, "rows": rows}, separators=(",", ":")) + ";\n",
                   encoding="utf-8")
    return len(rows)


def main():
    cache = json.loads(CACHE.read_text(encoding="utf-8")) if CACHE.exists() else {}
    land_boxes = cache.get("land_boxes")
    if land_boxes is None:  # derive from the elevation-only pass of the previous version, if present
        boxes = cache.get("boxes", {})
        land_boxes = [k for k, pts in boxes.items() if any(p[2] for p in pts)] if boxes else [f"{a},{o}" for a in range(-90, 90, 10) for o in range(-180, 180, 10)]
        cache = {"land_boxes": land_boxes, "done": [], "data": {}}
    done, data = set(cache["done"]), cache["data"]
    todo = [b for b in land_boxes if b not in done]
    print(f"{len(land_boxes)} land boxes, {len(todo)} to go")

    lock = threading.Lock()

    def assign_coarse(p, js, a0, o0):
        """SW and UV come from CERES SYN1deg on a 1° grid, so their points never sit on the 2.5° grid:
        give every land cell of the box the value of the nearest coarse point (within 1°)."""
        fill = js.get("header", {}).get("fill_value", -999)
        feats = [(f["geometry"]["coordinates"][1], f["geometry"]["coordinates"][0], f["properties"]["parameter"][p]) for f in js.get("features", [])]
        for key, rec in data.items():
            lat, lon = map(float, key.split(","))
            if not (a0 <= lat <= a0 + 10 and o0 <= lon <= o0 + 10) or not feats:
                continue
            flat, flon, v = min(feats, key=lambda f: (f[0] - lat) ** 2 + (f[1] - lon) ** 2)
            if (flat - lat) ** 2 + (flon - lon) ** 2 > 1.0:
                continue
            if p == "ALLSKY_SFC_SW_DWN":
                m = [v[k] for k in MONTHS if v[k] != fill]
                if m:
                    rec["SW"], rec["SW_MIN"], rec["SW_MAX"] = v["ANN"], min(m), max(m)
            else:
                rec[p] = None if v["ANN"] == fill else v["ANN"]

    def do_box(box, params=PARAMS):
        a0, o0 = map(int, box.split(","))
        got = {}
        for p in params:
            got[p] = get(URL.format(a0=a0, a1=a0 + 10, o0=o0, o1=o0 + 10, p=p))
            time.sleep(0.3)
        with lock:
            for p, js in got.items():  # fine (MERRA-2) parameters first, coarse ones last
                if p in COARSE:
                    assign_coarse(p, js, a0, o0)
                    continue
                fill = js.get("header", {}).get("fill_value", -999)
                for f in js.get("features", []):
                    lon, lat, z = f["geometry"]["coordinates"]
                    if not z or not on_grid(lat, lon):
                        continue  # ocean or not on the 2.5° grid
                    v = f["properties"]["parameter"][p]
                    rec = data.setdefault(f"{lat},{lon}", {"z": z})
                    rec[p] = None if v["ANN"] == fill else v["ANN"]
            if params is PARAMS:
                cache["done"].append(box)
            else:
                cache.setdefault("done_coarse", []).append(box)
        return box

    # repair pass for caches built before the coarse-grid fix
    redo = [b for b in land_boxes if b in done and b not in set(cache.get("done_coarse", []))
            and any(len(v) < len(PARAMS) + 3 for k, v in data.items())]
    if redo and not todo:
        print(f"filling SW/UV for {len(redo)} boxes")
        with ThreadPoolExecutor(3) as ex:
            for n, _ in enumerate(ex.map(lambda b: do_box(b, COARSE), redo), 1):
                if n % 20 == 0 or n == len(redo):
                    with lock:
                        CACHE.write_text(json.dumps(cache), encoding="utf-8")
                        cells = write_grid(data)
                    print(f"[coarse {n}/{len(redo)}] {cells} complete cells")

    with ThreadPoolExecutor(3) as ex:  # 3 boxes in flight; get() backs off on HTTP 429
        for n, box in enumerate(ex.map(do_box, todo), 1):
            if n % 10 == 0 or n == len(todo):
                with lock:
                    CACHE.write_text(json.dumps(cache), encoding="utf-8")
                    cells = write_grid(data)
                print(f"[{n}/{len(todo)}] {cells} land cells so far")
    print("finished:", write_grid(data), "cells")


if __name__ == "__main__":
    main()
